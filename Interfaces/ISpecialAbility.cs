namespace BattleGame.Interfaces;

// Контракт спецспособности. Реализуют только юниты, умеющие атаковать с дальних позиций.
// Принцип I (SOLID): не заставляем обычных пехотинцев реализовывать стрельбу.
public interface ISpecialAbility
{
    // Максимальная дальность: юнит на позиции N стреляет, если Range >= N
    int Range { get; }

    // Базовая сила способности до вычета защиты цели
    int Power { get; }

    // Применить способность к цели, вернуть нанесённый урон
    int UseAbility(Units.Unit target);
}
